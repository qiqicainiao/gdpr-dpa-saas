export function renderResult(root, data, meta) {
  const items = Array.isArray(data.items) ? data.items : [];
  const summary = data.summary || {};

  fillText(root.querySelector('#result-summary-text'), buildSummaryText(items, summary, meta));

  fillText(root.querySelector('#stat-clauses'), String(items.length));
  fillText(root.querySelector('#stat-warnings'), String(typeof summary.warning_count === 'number' ? summary.warning_count : 0));
  fillText(root.querySelector('#stat-template'), summary.template_version ? String(summary.template_version) : '—');

  const list = root.querySelector('#clause-list');
  if (!list) return;
  list.textContent = '';
  items.forEach((item) => {
    list.appendChild(buildClauseCard(item));
  });
}

export function buildDocumentText(data) {
  const summary = data.summary || {};
  const items = Array.isArray(data.items) ? data.items : [];
  const lines = [];

  lines.push(summary.document_title ? String(summary.document_title) : 'Data Processing Agreement');
  lines.push('');
  lines.push('Template version: ' + (summary.template_version ? String(summary.template_version) : '—'));
  lines.push('');

  items.forEach((item, index) => {
    lines.push(index + 1 + '. ' + String(item.title || ''));
    lines.push('');
    lines.push(String(item.body || ''));
    lines.push('');
  });

  lines.push('Draft generated by GDPR DPA Generator for SaaS. Review by qualified counsel is required before signature.');
  return lines.join('\n');
}

export async function copyToClipboard(text) {
  try {
    if (navigator.clipboard && window.isSecureContext) {
      await navigator.clipboard.writeText(text);
      return true;
    }
  } catch (error) {
    /* fall through */
  }

  try {
    const area = document.createElement('textarea');
    area.value = text;
    area.setAttribute('readonly', 'readonly');
    area.style.position = 'fixed';
    area.style.top = '-1000px';
    document.body.appendChild(area);
    area.select();
    const ok = document.execCommand('copy');
    document.body.removeChild(area);
    return ok;
  } catch (error) {
    return false;
  }
}

function buildClauseCard(item) {
  const card = document.createElement('li');
  card.className = 'clause-card';
  card.setAttribute('data-clause-key', String(item.clause_key || ''));

  const head = document.createElement('div');
  head.className = 'clause-head';

  const titleWrap = document.createElement('div');
  const metaLine = document.createElement('p');
  metaLine.className = 'clause-meta';
  metaLine.textContent = 'Clause ' + String(item.position || '');
  const title = document.createElement('h3');
  title.className = 'clause-title';
  title.textContent = String(item.title || '');
  titleWrap.appendChild(metaLine);
  titleWrap.appendChild(title);

  const badges = document.createElement('div');
  badges.className = 'clause-badges';
  if (item.status === 'warning') {
    badges.appendChild(badge('Needs review', 'warning'));
  }
  if (item.required === false) {
    badges.appendChild(badge('Optional', 'neutral'));
  }

  head.appendChild(titleWrap);
  head.appendChild(badges);

  const body = document.createElement('p');
  body.className = 'clause-body';
  body.textContent = String(item.body || '');

  card.appendChild(head);
  card.appendChild(body);

  const alternatives = Array.isArray(item.alternatives) ? item.alternatives : [];
  if (alternatives.length > 0) {
    card.appendChild(buildAlternatives(alternatives, title, body));
  }

  return card;
}

function buildAlternatives(alternatives, titleNode, bodyNode) {
  const wrapper = document.createElement('details');
  wrapper.className = 'clause-alternatives';

  const summary = document.createElement('summary');
  summary.textContent = 'Alternative wording (' + alternatives.length + ')';
  wrapper.appendChild(summary);

  alternatives.forEach((alt, index) => {
    const button = document.createElement('button');
    button.type = 'button';
    button.className = 'btn btn-quiet alt-button';
    button.textContent = 'Use alternative ' + (index + 1) + (alt.clause_variant ? ' · ' + String(alt.clause_variant) : '');
    button.addEventListener('click', () => {
      titleNode.textContent = String(alt.title || alt.clause_variant || '');
      bodyNode.textContent = String(alt.body || '');
      wrapper.querySelectorAll('.alt-button').forEach((item) => item.classList.remove('is-active'));
      button.classList.add('is-active');
    });
    wrapper.appendChild(button);
  });

  return wrapper;
}

function badge(text, tone) {
  const node = document.createElement('span');
  node.className = 'clause-badge';
  node.setAttribute('data-tone', tone);
  node.textContent = text;
  return node;
}

function buildSummaryText(items, summary, meta) {
  const parts = [];
  parts.push(items.length + (items.length === 1 ? ' clause' : ' clauses') + ' generated');

  const coverage = typeof summary.coverage_ratio === 'number'
    ? Math.round(summary.coverage_ratio * 100) + '% template coverage'
    : 'coverage not applicable';
  parts.push(coverage);

  if (summary.warning_count > 0) {
    parts.push(summary.warning_count + ' to review');
  }

  if (meta && meta.traceTail) {
    parts.push('trace ' + meta.traceTail);
  }

  return parts.join(' · ');
}

function fillText(node, text) {
  if (node) node.textContent = text;
}
